"""
Build docs/comparison.md from the latest result file of each target in evals/results/.
The table is generated, never hand-edited, so every number traces back to a result file.

  python evals/generate_comparison.py [--results evals/results] [--out docs/comparison.md]
"""
import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
EXCLUDE_PREFIXES = ("oracle",)        # scorer self-checks don't belong in the portfolio table


def latest_per_target(results: Path) -> list[dict]:
    latest: dict[str, dict] = {}
    for p in sorted(results.glob("*.json")):
        r = json.loads(p.read_text(encoding="utf-8"))
        t = r["meta"]["target"]
        if t.startswith(EXCLUDE_PREFIXES):
            continue
        if t not in latest or r["meta"]["started_at"] > latest[t]["meta"]["started_at"]:
            r["_file"] = p.name
            latest[t] = r
    return [latest[t] for t in sorted(latest)]


def pct(x) -> str:
    return "–" if x is None else f"{x * 100:.0f}%"


def render(reports: list[dict]) -> str:
    lines = ["# Comparison across implementations", "",
             "<!-- GENERATED by evals/generate_comparison.py from evals/results/*.json. Do not edit by hand. -->", ""]
    if not reports:
        lines += ["No eval results yet. Run `make eval` in a project, then `python evals/generate_comparison.py`."]
        return "\n".join(lines) + "\n"
    lines += ["Same cases (`evals/cases.yaml`), same fixtures, same contract. Each case runs several times "
              "because agents are non-deterministic; pass rate is over all runs.", "",
              "| Implementation | Pass rate | Cases always passing | Category acc. | KB match acc. | Median latency | "
              "Cost / run | Tokens / run | Model | Commit | Date |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in reports:
        s, m = r["summary"], r["meta"]
        lat = f"{s['latency_ms_median'] / 1000:.1f} s" if s["latency_ms_median"] is not None else "–"
        cost = f"${s['cost_usd_per_run']:.4f}" if s["cost_usd_per_run"] is not None else "–"
        lines.append(f"| {m['target']} | {pct(s['pass_rate'])} ({s['runs_passed']}/{s['runs']}) | "
                     f"{s['cases_always_passing']}/{s['cases']} | {pct(s['category_accuracy'])} | {pct(s['kb_accuracy'])} | "
                     f"{lat} | {cost} | {s['tokens_per_run'] or '–'} | {', '.join(m['models']) or '–'} | "
                     f"`{m['git_sha']}` | {m['started_at'][:10]} |")
    case_ids = sorted({c["id"] for r in reports for c in r["cases"]})
    lines += ["", "## Pass rate per case", "", "| Case | " + " | ".join(r["meta"]["target"] for r in reports) + " |",
              "|---|" + "---|" * len(reports)]
    for cid in case_ids:
        cells = []
        for r in reports:
            c = next((c for c in r["cases"] if c["id"] == cid), None)
            cells.append(pct(c["pass_rate"]) if c else "–")
        lines.append(f"| {cid} | " + " | ".join(cells) + " |")
    lines += ["", "Sources: " + ", ".join(f"`evals/results/{r['_file']}`" for r in reports)]
    return "\n".join(lines) + "\n"


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(REPO / "evals" / "results"))
    ap.add_argument("--out", default=str(REPO / "docs" / "comparison.md"))
    args = ap.parse_args(argv)
    md = render(latest_per_target(Path(args.results)))
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(md, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
